// The commit, pull request title, and product version rules in
// docs/CHANGE_CONTRACT.md, kept separate from the CLI in
// check-commit-contract.mjs so they can be tested against crafted input.
//
// The contract exists so `git log --oneline` and the pull request list stay
// readable without rewriting any history: every rule below applies to commits a
// pull request *adds*, never to commits already on the base branch.

export const COMMIT_TYPES = Object.freeze([
  "build",
  "chore",
  "ci",
  "docs",
  "feat",
  "fix",
  "perf",
  "refactor",
  "revert",
  "style",
  "test",
]);

// A generous ceiling rather than the traditional 50: this repository routinely
// names an owner and an issue in the subject, and truncating that to fit a
// convention would lose the part a later reader needs.
export const MAX_HEADER_LENGTH = 100;

const HEADER_PATTERN = /^(?<type>[a-z]+)(?:\((?<scope>[^()]+)\))?(?<breaking>!)?: (?<subject>.+)$/;
const SCOPE_PATTERN = /^[a-z0-9][a-z0-9._/-]*$/;

// GitHub's own revert button writes exactly this subject. Rejecting it would
// mean hand-editing the one commit most likely to be made under pressure.
const REVERT_PATTERN = /^Revert ".+"$/;

const BREAKING_FOOTER_PATTERN = /^BREAKING CHANGE: \S/m;

/**
 * Describes why a header fails the contract, or null when it passes.
 *
 * `body` is only consulted for the `BREAKING CHANGE:` footer, so a caller that
 * has no body available (a pull request title) may omit it and will be told to
 * supply the footer elsewhere.
 */
export function findHeaderViolation(header, { body = "" } = {}) {
  if (typeof header !== "string" || header.trim() === "") {
    return "the subject line is empty.";
  }
  if (header !== header.trim()) {
    return "the subject line has leading or trailing whitespace.";
  }
  if (header.length > MAX_HEADER_LENGTH) {
    return `the subject line is ${header.length} characters; the limit is ${MAX_HEADER_LENGTH}.`;
  }

  const match = HEADER_PATTERN.exec(header);
  if (!match) {
    return (
      "it does not match '<type>(<optional scope>): <subject>'. " +
      `Allowed types: ${COMMIT_TYPES.join(", ")}.`
    );
  }

  const { type, scope, breaking, subject } = match.groups;
  if (!COMMIT_TYPES.includes(type)) {
    return `'${type}' is not an allowed type. Allowed types: ${COMMIT_TYPES.join(", ")}.`;
  }
  if (scope !== undefined && !SCOPE_PATTERN.test(scope)) {
    return `scope '${scope}' must be lowercase and may contain only letters, digits, '.', '_', '/', and '-'.`;
  }
  if (subject.endsWith(".")) {
    return "the subject ends with a period.";
  }
  if (breaking && !BREAKING_FOOTER_PATTERN.test(body)) {
    return "it is marked breaking with '!' but has no 'BREAKING CHANGE: <consequence>' footer.";
  }

  return null;
}

function isBotIdentity(value) {
  return typeof value === "string" && /\[bot\]/.test(value);
}

/**
 * Validates the commits a pull request adds.
 *
 * `commits` are objects of `{ sha, parents, author, email, subject, body }`.
 * Merge commits and dependency-bot commits are exempt: their subjects are
 * generated by GitHub or by the bot, and neither can be corrected by the
 * contributor being blocked.
 */
export function findCommitViolations(commits) {
  const violations = [];

  for (const commit of commits) {
    const shortSha = (commit.sha ?? "").slice(0, 8) || "(unknown)";

    if ((commit.parents?.length ?? 0) > 1) {
      continue;
    }
    if (isBotIdentity(commit.author) || isBotIdentity(commit.email)) {
      continue;
    }
    if (REVERT_PATTERN.test(commit.subject ?? "")) {
      continue;
    }

    const violation = findHeaderViolation(commit.subject, { body: commit.body ?? "" });
    if (violation) {
      violations.push(`commit ${shortSha} "${commit.subject}": ${violation}`);
    }
  }

  return violations;
}

/**
 * Validates a pull request title.
 *
 * The title is the merge commit's message body, so it is held to the same
 * grammar as a commit subject. A bot-authored pull request is exempt for the
 * same reason its commits are.
 */
export function findPullRequestTitleViolations(title, { author = "", body = "" } = {}) {
  if (isBotIdentity(author)) {
    return [];
  }
  if (REVERT_PATTERN.test(title ?? "")) {
    return [];
  }

  const violation = findHeaderViolation(title, { body });
  return violation ? [`pull request title "${title}": ${violation}`] : [];
}
